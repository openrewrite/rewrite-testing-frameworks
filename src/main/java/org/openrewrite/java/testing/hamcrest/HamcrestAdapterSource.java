package org.openrewrite.java.testing.hamcrest;

import java.util.*;

/**
 * The source of the {@code HamcrestAdapters} class that the migration generates once per module, holding only the
 * adapters that module's tests need. Each adapter keeps the behavior of a Hamcrest matcher that AssertJ has no
 * counterpart for, written against AssertJ and the JDK alone.
 */
final class HamcrestAdapterSource {
    static final String CLASS_NAME = "HamcrestAdapters";

    /**
     * Marks the generated class, so that a later run adds to it rather than to a class of the project's own that
     * happens to have the same name.
     */
    static final String MARKER = "Generated by the OpenRewrite migration from Hamcrest to AssertJ.";

    static final String SATISFYING = "satisfying";
    static final String SAME_PROPERTY_VALUES_AS = "samePropertyValuesAs";
    static final String PROPERTY = "property";
    static final String HAS_XPATH = "hasXPath";
    static final String EVALUATE_XPATH = "evaluateXPath";
    static final String EVENT_FROM = "eventFrom";
    static final String DESCRIPTION = "description";
    static final String IN_RELATIVE_ORDER = "inRelativeOrder";

    private static final Map<String, String> METHODS = new LinkedHashMap<>();
    private static final Map<String, Set<String>> IMPORTS = new HashMap<>();

    static {
        add(SATISFYING, setOf("java.util.function.Consumer", "org.assertj.core.api.Condition"),
                "    /**\n" +
                "     * A condition that holds when the requirements pass, for negating requirements that AssertJ has no\n" +
                "     * opposite of, as Hamcrest's {@code not(..)} did. The condition takes any object, so that it fits\n" +
                "     * {@code isNot(..)} of every assertion, and hands the requirements the actual value of the assertion\n" +
                "     * as the type they are written for.\n" +
                "     */\n" +
                "    @SuppressWarnings(\"unchecked\")\n" +
                "    public static <T> Condition<Object> satisfying(Consumer<? super T> requirements) {\n" +
                "        return new Condition<>(actual -> {\n" +
                "            try {\n" +
                "                requirements.accept((T) actual);\n" +
                "                return true;\n" +
                "            } catch (AssertionError e) {\n" +
                "                return false;\n" +
                "            }\n" +
                "        }, \"satisfying the requirements\");\n" +
                "    }\n");
        add(PROPERTY, setOf("java.beans.Introspector", "java.beans.PropertyDescriptor", "java.lang.reflect.Method"),
                "    /**\n" +
                "     * Reads a JavaBean property, as Hamcrest's {@code hasProperty(name, matcher)} did.\n" +
                "     */\n" +
                "    @SuppressWarnings(\"unchecked\")\n" +
                "    public static <V> V property(Object bean, String name) {\n" +
                "        try {\n" +
                "            for (PropertyDescriptor descriptor : Introspector.getBeanInfo(bean.getClass()).getPropertyDescriptors()) {\n" +
                "                Method read = descriptor.getReadMethod();\n" +
                "                if (descriptor.getName().equals(name) && read != null) {\n" +
                "                    return (V) read.invoke(bean);\n" +
                "                }\n" +
                "            }\n" +
                "        } catch (Exception e) {\n" +
                "            throw new AssertionError(\"Could not read property \" + name + \" of \" + bean, e);\n" +
                "        }\n" +
                "        throw new AssertionError(\"No readable property \" + name + \" on \" + bean);\n" +
                "    }\n");
        add(SAME_PROPERTY_VALUES_AS, setOf("java.beans.Introspector", "java.beans.PropertyDescriptor",
                        "java.lang.reflect.Method", "java.util.Arrays", "java.util.HashMap", "java.util.HashSet",
                        "java.util.List", "java.util.Map", "java.util.Objects", "java.util.Set",
                        "org.assertj.core.api.Condition"),
                "    /**\n" +
                "     * A condition that holds when the actual bean has the same readable properties as the expected one, with\n" +
                "     * equal values, as Hamcrest's {@code samePropertyValuesAs(..)} did.\n" +
                "     */\n" +
                "    public static <T> Condition<T> samePropertyValuesAs(T expected, String... ignoredProperties) {\n" +
                "        List<String> ignored = Arrays.asList(ignoredProperties);\n" +
                "        return new Condition<>(actual -> {\n" +
                "            if (actual == null || !expected.getClass().isAssignableFrom(actual.getClass())) {\n" +
                "                return false;\n" +
                "            }\n" +
                "            Map<String, Method> expectedProperties = readableProperties(expected.getClass(), ignored);\n" +
                "            Set<String> actualProperties = new HashSet<>(readableProperties(actual.getClass(), ignored).keySet());\n" +
                "            actualProperties.removeAll(expectedProperties.keySet());\n" +
                "            if (!actualProperties.isEmpty()) {\n" +
                "                return false;\n" +
                "            }\n" +
                "            try {\n" +
                "                for (Method read : expectedProperties.values()) {\n" +
                "                    if (!Objects.deepEquals(read.invoke(expected), read.invoke(actual))) {\n" +
                "                        return false;\n" +
                "                    }\n" +
                "                }\n" +
                "            } catch (Exception e) {\n" +
                "                throw new AssertionError(\"Could not compare the properties of \" + actual, e);\n" +
                "            }\n" +
                "            return true;\n" +
                "        }, \"same property values as %s\", expected);\n" +
                "    }\n" +
                "\n" +
                "    private static Map<String, Method> readableProperties(Class<?> type, List<String> ignored) {\n" +
                "        Map<String, Method> properties = new HashMap<>();\n" +
                "        try {\n" +
                "            for (PropertyDescriptor descriptor : Introspector.getBeanInfo(type, Object.class).getPropertyDescriptors()) {\n" +
                "                if (descriptor.getReadMethod() != null && !ignored.contains(descriptor.getName())) {\n" +
                "                    properties.put(descriptor.getName(), descriptor.getReadMethod());\n" +
                "                }\n" +
                "            }\n" +
                "        } catch (Exception e) {\n" +
                "            throw new AssertionError(\"Could not read the properties of \" + type, e);\n" +
                "        }\n" +
                "        return properties;\n" +
                "    }\n");
        add(HAS_XPATH, setOf("javax.xml.namespace.NamespaceContext", "javax.xml.xpath.XPath",
                        "javax.xml.xpath.XPathConstants", "javax.xml.xpath.XPathFactory", "org.assertj.core.api.Condition",
                        "org.w3c.dom.Node"),
                "    /**\n" +
                "     * A condition that holds when the XPath expression selects a node, as Hamcrest's {@code hasXPath(..)} did.\n" +
                "     */\n" +
                "    public static Condition<Node> hasXPath(String expression, NamespaceContext namespaces) {\n" +
                "        return new Condition<>(node -> {\n" +
                "            try {\n" +
                "                XPath xpath = XPathFactory.newInstance().newXPath();\n" +
                "                if (namespaces != null) {\n" +
                "                    xpath.setNamespaceContext(namespaces);\n" +
                "                }\n" +
                "                return xpath.evaluate(expression, node, XPathConstants.NODE) != null;\n" +
                "            } catch (Exception e) {\n" +
                "                throw new AssertionError(\"Could not evaluate \" + expression, e);\n" +
                "            }\n" +
                "        }, \"an XML document with XPath %s\", expression);\n" +
                "    }\n");
        add(EVALUATE_XPATH, setOf("javax.xml.namespace.NamespaceContext", "javax.xml.xpath.XPath",
                        "javax.xml.xpath.XPathFactory", "org.w3c.dom.Node"),
                "    /**\n" +
                "     * The string value of an XPath expression, which Hamcrest's {@code hasXPath(expression, matcher)} matched.\n" +
                "     */\n" +
                "    public static String evaluateXPath(Node node, String expression, NamespaceContext namespaces) {\n" +
                "        try {\n" +
                "            XPath xpath = XPathFactory.newInstance().newXPath();\n" +
                "            if (namespaces != null) {\n" +
                "                xpath.setNamespaceContext(namespaces);\n" +
                "            }\n" +
                "            return xpath.evaluate(expression, node);\n" +
                "        } catch (Exception e) {\n" +
                "            throw new AssertionError(\"Could not evaluate \" + expression, e);\n" +
                "        }\n" +
                "    }\n");
        add(EVENT_FROM, setOf("java.util.EventObject", "org.assertj.core.api.Condition"),
                "    /**\n" +
                "     * A condition that holds for an event of the type from the source, as Hamcrest's {@code eventFrom(..)} did.\n" +
                "     */\n" +
                "    public static Condition<Object> eventFrom(Class<? extends EventObject> eventType, Object source) {\n" +
                "        return new Condition<>(event -> eventType.isInstance(event) && ((EventObject) event).getSource() == source,\n" +
                "                \"an event of type %s from %s\", eventType.getName(), source);\n" +
                "    }\n");
        add(DESCRIPTION, setOf("java.util.regex.Matcher", "java.util.regex.Pattern"),
                "    /**\n" +
                "     * Fills the {@code %0}, {@code %1}, .. placeholders of a description, as Hamcrest's {@code describedAs(..)} did.\n" +
                "     */\n" +
                "    public static String description(String template, Object... values) {\n" +
                "        Matcher placeholder = Pattern.compile(\"%([0-9]+)\").matcher(template);\n" +
                "        StringBuffer description = new StringBuffer();\n" +
                "        while (placeholder.find()) {\n" +
                "            placeholder.appendReplacement(description,\n" +
                "                    Matcher.quoteReplacement(String.valueOf(values[Integer.parseInt(placeholder.group(1))])));\n" +
                "        }\n" +
                "        return placeholder.appendTail(description).toString();\n" +
                "    }\n");
        add(IN_RELATIVE_ORDER, setOf("java.util.Iterator", "java.util.function.Consumer", "org.assertj.core.api.Condition"),
                "    /**\n" +
                "     * A condition that holds when, for each requirement in turn, a later element than the one that met the\n" +
                "     * previous requirement meets it, as Hamcrest's {@code containsInRelativeOrder(matchers)} did.\n" +
                "     */\n" +
                "    @SafeVarargs\n" +
                "    public static <E> Condition<Iterable<? extends E>> inRelativeOrder(Consumer<? super E>... requirements) {\n" +
                "        return new Condition<>(actual -> {\n" +
                "            Iterator<? extends E> elements = actual.iterator();\n" +
                "            for (Consumer<? super E> requirement : requirements) {\n" +
                "                boolean met = false;\n" +
                "                while (!met && elements.hasNext()) {\n" +
                "                    try {\n" +
                "                        requirement.accept(elements.next());\n" +
                "                        met = true;\n" +
                "                    } catch (AssertionError e) {\n" +
                "                        // try the next element\n" +
                "                    }\n" +
                "                }\n" +
                "                if (!met) {\n" +
                "                    return false;\n" +
                "                }\n" +
                "            }\n" +
                "            return true;\n" +
                "        }, \"elements meeting the requirements in relative order\");\n" +
                "    }\n");
    }

    private HamcrestAdapterSource() {
    }

    private static void add(String name, Set<String> imports, String source) {
        METHODS.put(name, source);
        IMPORTS.put(name, imports);
    }

    private static Set<String> setOf(String... values) {
        return new TreeSet<>(Arrays.asList(values));
    }

    static boolean isAdapter(String name) {
        return METHODS.containsKey(name);
    }

    /**
     * @param packageName the package to declare the class in, empty for none
     * @param adapters    the adapters to include; all of them when empty, so that a template can type its calls
     */
    static String source(String packageName, Collection<String> adapters) {
        Collection<String> included = adapters.isEmpty() ? METHODS.keySet() : adapters;
        Set<String> imports = new TreeSet<>();
        for (String name : included) {
            imports.addAll(IMPORTS.get(name));
        }
        StringBuilder source = new StringBuilder();
        if (!packageName.isEmpty()) {
            source.append("package ").append(packageName).append(";\n\n");
        }
        for (String anImport : imports) {
            source.append("import ").append(anImport).append(";\n");
        }
        source.append("\n/**\n * ").append(MARKER).append("\n * <p>\n")
                .append(" * Each method keeps the behavior of a Hamcrest matcher that AssertJ has no direct counterpart for.\n")
                .append(" */\n")
                .append("public final class ").append(CLASS_NAME).append(" {\n\n")
                .append("    private ").append(CLASS_NAME).append("() {\n    }\n");
        for (Map.Entry<String, String> method : METHODS.entrySet()) {
            if (included.contains(method.getKey())) {
                source.append('\n').append(method.getValue());
            }
        }
        return source.append("}\n").toString();
    }
}
